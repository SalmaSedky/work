--WH TO SHOP (INBOUND - from shop perspective)
SELECT 
'WH TO SHOP_INBOUND' TRANSACTION_TYPE, 
TO_CHAR(S.SUPNO) ORIGINATING_STORE_ID, S.SUPNAM1 ORIGINATING_STORE_NAME, 
O.OFFNO RECEIVING_STORE_ID, O.OFFNAM RECEIVING_STORE_NAME, O.OFFNAM2 RECEIVING_STORE_TYPE,
M.MATNO SIC, M.MATNAM SIC_DESCRIPTION, 
OD.UPDSTMP TRANSACTION_DATE, 
OD.DELQTY DELIVERED_QUANTITY, 
NVL(M.Empprice,0) AUC, 
(OD.DELQTY * NVL(M.Empprice,0)) TOTAL_COST,
'' SERIAL, '' SUB_REQ_ID, TO_CHAR(OH.OrdID) REFERENCENO, D.DELNOTENO CSSREFERENCE
FROM WINPROD.ORDHDR OH
INNER JOIN WINPROD.ORDDTL OD ON OH.ORDiD = OD.ORDID
INNER JOIN WINPROD.MATERIAL M ON OD.MATNO = M.MATNO AND M.TREEID IN (0,1) 
INNER JOIN WINPROD.OFFICE O ON OD.TREEID = O.TREEID
INNER JOIN WINPROD.SUPPLIER S ON OD.SUPID = S.GID
LEFT OUTER JOIN (SELECT distinct REFNO, DELNOTENO FROM WINPROD.DBOD) D ON D.REFNO = OH.OrdID
WHERE OD.ORDSTATUS='C'
AND TRUNC(OD.UPDSTMP) BETWEEN '01-NOV-25'  AND '30-NOV-25'

UNION ALL

