-- SALES/RETURN/CANCEL Transactions (no INBOUND/OUTBOUND needed)
SELECT 
        (CASE
            WHEN VD.VOUTYPE = 'V' THEN 'SALE'
            WHEN VD.VOUTYPE = 'R' THEN 'RETURN'
            WHEN VD.VOUTYPE = 'S' THEN 'CANCEL'
        END) TRANSACTION_TYPE, 
        TO_CHAR(O.OFFNO) ORIGINATING_STORE_ID, O.OFFNAM ORIGINATING_STORE_NAME, 
        '' RECEIVING_STORE_ID, '' RECEIVING_STORE_NAME, '' RECEIVING_STORE_TYPE,
        M.MATNO SIC, M.MATNAM SIC_DESCRIPTION, 
        TRUNC(VH.POSDAT) TRANSACTION_DATE, 
        VD.AM DELIVERED_QUANTITY, 
        NVL(VD.EMPPRICE,M.EMPPRICE) AUC, 
        ROUND(VD.AM * NVL(VD.EMPPRICE,M.EMPPRICE),2) TOTAL_COST,
        SERTXT SERIAL, V2FF.FFVALUE SUB_REQ_ID, TO_CHAR(VD.COUPONCODE) REFERENCENO, '' CSSREFERENCE
    FROM 
        WINPROD.VOUHDR VH
        INNER JOIN WINPROD.VOUDTL VD ON VH.JOUID = VD.JOUID AND VH.TREEID = VD.TREEID
        INNER JOIN WINPROD.OFFICE O ON O.TREEID = VD.TREEID
        INNER JOIN WINPROD.MATERIAL M ON M.GID = VD.MATID AND M.STOCKCTRL='Y'
        INNER JOIN WINPROD.WAREGROUP WG ON WG.GID = VD.WGID 
        INNER JOIN WINPROD.MATGROUP MG ON MG.GID = M.MGID
        INNER JOIN WINPROD.STOCK S ON S.GID = VD.STOCKID
        INNER JOIN WINPROD.MATUNIT MU ON MU.GID = M.UNITID
        LEFT OUTER JOIN WINPROD.VOU2FLEXFIELD V2FF ON V2FF.JOUID = VD.JOUID AND V2FF.DTLID = VD.DTLID AND FFID=24 --24 is sub request id
    WHERE 
        VH.VOUTYPE in ('V','R','S')
        AND TRUNC(VH.POSDAT) BETWEEN '01-NOV-25'  AND '30-NOV-25'
 
UNION ALL
 
-- STOCK TAKE (no INBOUND/OUTBOUND needed)
    SELECT 
        CASE 
            WHEN  MV.QTY < 0 THEN 'STOCK TAKE ADJUSTMENTS PHYSICAL SHORTAGE AND SYSTEM EXCESS' 
            WHEN  MV.QTY > 0 THEN 'STOCK TAKE ADJUSTMENTS PHYSICAL EXCESS and SYSTEM SHORTAGE' 
        END
        TRANSACTION_TYPE,     
        TO_CHAR(O.OFFNO) ORIGINATING_STORE_ID, O.OFFNAM ORIGINATING_STORE_NAME, 
        '' RECEIVING_STORE_ID, '' RECEIVING_STORE_NAME, '' RECEIVING_STORE_TYPE,
        M.MATNO SIC, M.MATNAM SIC_DESCRIPTION, 
        MV.UPDSTMP TRANSACTION_DATE, 
        abs(MV.QTY) DELIVERED_QUANTITY, 
        NVL(M.Empprice,0) AUC, 
        (abs(MV.QTY) * NVL(M.Empprice,0)) TOTAL_COST,
        to_char(SERNOS) SERIAL, '' SUB_REQ_ID, TO_CHAR(MV.EXPID1) REFERENCENO, '' CSSREFERENCE
    FROM WINPROD.MATMOVE MV
        INNER JOIN WINPROD.MATMOVETYPE MVT ON MV.MVTYPEID=MVT.GID AND MVT.MMTCODE IN ('INV') 
                                                AND mv.status ='O' AND MV.MVNO2 is not null
        AND MV.QTY <> 0 --AND mv.EXPID1 IS NOT NULL
        INNER JOIN WINPROD.MATERIAL M ON MV.MATID = M.GID AND M.STOCKCTRL='Y'
        INNER JOIN WINPROD.OFFICE o ON MV.TREEID = O.TREEID
        INNER JOIN WINPROD.MATGROUP MG ON MG.GID = M.MGID
        INNER JOIN WINPROD.STOCK S ON S.GID = MV.STOCKID
        INNER JOIN WINPROD.MATUNIT MU ON MU.GID = M.UNITID
    WHERE 
    trunc(MV.UPDSTMP) BETWEEN '01-NOV-25'  AND '30-NOV-25'
    AND ROUND(MV.QTY * M.EMPPRICE, 2) <> 0;
